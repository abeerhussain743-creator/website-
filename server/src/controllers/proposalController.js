function pushEvent(proposal, type, label, meta = {}) {
  proposal.events.push({ type, label, meta, at: new Date() });
}

export async function listProposals(req, res) {
  const proposals = await Proposal.find({ organization: req.user.organization })
    .populate('client', 'companyName contactName contactEmail')
    .populate('call', 'title status')
    .sort({ updatedAt: -1 });
  return res.json({ proposals });
}

