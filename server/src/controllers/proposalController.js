export async function trackPublicEvent(req, res) {
  try {
    const proposal = await Proposal.findOne({ slug: req.params.slug }).populate('client').populate('owner');
    if (!proposal) return res.status(404).json({ message: 'Proposal not found' });

    const { type, seconds = 0 } = req.body;
    const now = new Date();

    if (type === 'opened') {
      if (!proposal.firstOpenedAt) proposal.firstOpenedAt = now;
      proposal.lastViewedAt = now;
      proposal.openCount += 1;
      if (['sent', 'viewed'].includes(proposal.status)) proposal.status = 'viewed';
      const label = proposal.openCount === 1
        ? `${proposal.client.contactName || 'Client'} opened proposal`
        : `${proposal.client.contactName || 'Client'} returned to proposal`;
      pushEvent(proposal, proposal.openCount === 1 ? 'opened' : 'returned', label);
      await Notification.create({
        organization: proposal.organization,
        user: proposal.owner._id || proposal.owner,
        type: 'proposal_opened',
        title: 'Proposal opened',
        body: label,
        link: `/proposals/${proposal._id}`,
      });
    }

    if (type === 'viewed_pricing') {
      proposal.lastViewedAt = now;
      pushEvent(proposal, 'viewed_pricing', 'Viewed pricing');
    }

    if (type === 'heartbeat') {
      proposal.totalViewTimeSeconds += Number(seconds) || 0;
      proposal.lastViewedAt = now;
    }

    if (type === 'requested_changes') {
      proposal.status = 'changes_requested';
      proposal.changeRequest = req.body.message || 'Client requested changes';
      pushEvent(proposal, 'requested_changes', 'Requested changes', { message: proposal.changeRequest });
      await Notification.create({
        organization: proposal.organization,
        user: proposal.owner._id || proposal.owner,
        type: 'proposal_changes',
        title: 'Changes requested',
        body: `${proposal.client.companyName} requested changes to the proposal.`,
        link: `/proposals/${proposal._id}`,
      });
    }

    if (type === 'accepted') {
      proposal.status = 'accepted';
      proposal.acceptedAt = now;
      pushEvent(proposal, 'accepted', 'Accepted proposal');
      await Call.findByIdAndUpdate(proposal.call, { status: 'won' });
      await Client.findByIdAndUpdate(proposal.client._id || proposal.client, { status: 'won' });
      await Notification.create({
        organization: proposal.organization,
        user: proposal.owner._id || proposal.owner,
        type: 'proposal_accepted',
        title: 'Deal won',
        body: `${proposal.client.companyName} accepted — $${Number(proposal.investment).toLocaleString()}`,
        link: `/proposals/${proposal._id}`,
      });
    }

    if (type === 'declined') {
      proposal.status = 'declined';
      pushEvent(proposal, 'declined', 'Declined proposal');
      await Call.findByIdAndUpdate(proposal.call, { status: 'lost' });
      await Client.findByIdAndUpdate(proposal.client._id || proposal.client, { status: 'lost' });
    }

    await proposal.save();
    return res.json({ ok: true, status: proposal.status, totalViewTimeSeconds: proposal.totalViewTimeSeconds });
  } catch (error) {
    return res.status(500).json({ message: error.message });
  }
}

export async function followUp(req, res) {
  try {
    const proposal = await Proposal.findOne({ _id: req.params.id, organization: req.user.organization }).populate('client');
    if (!proposal) return res.status(404).json({ message: 'Proposal not found' });

    const tone = req.body.tone || 'professional';
    const day = Number(req.body.day) || 2;
    const draft = await generateFollowUp({ client: proposal.client, proposal, tone, day });

    if (req.body.markSent) {
      pushEvent(proposal, 'follow_up_sent', `Follow-up sent (${tone}, day ${draft.day})`);
      await proposal.save();
    }

    return res.json({ followUp: draft });
  } catch (error) {
    return res.status(500).json({ message: error.message });
  }
}

export async function downloadPdf(req, res) {
  try {
    const proposal = await Proposal.findOne({ _id: req.params.id, organization: req.user.organization })
      .populate('client')
      .populate('owner', 'name');
    if (!proposal) return res.status(404).json({ message: 'Proposal not found' });

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="${proposal.slug}.pdf"`);

    const doc = new PDFDocument({ margin: 50 });
    doc.pipe(res);
    doc.fontSize(22).text(proposal.client.companyName, { continued: false });
    doc.moveDown(0.3);
    doc.fontSize(14).fillColor('#334155').text(proposal.title);
    doc.moveDown();
    doc.fillColor('#0f172a').fontSize(11).text(`Prepared by ${proposal.owner.name}`);
    doc.text(`Investment: $${Number(proposal.investment).toLocaleString()}`);
    doc.text(`Timeline: ${proposal.timelineDisplay || 'TBD'}`);
    doc.moveDown();
    doc.fontSize(13).text('Project Overview');
    doc.fontSize(10).fillColor('#334155').text(proposal.content.projectOverview || '');
    doc.moveDown();
    doc.fillColor('#0f172a').fontSize(13).text('Scope of Work');
    (proposal.content.scopeOfWork || []).forEach((item) => {
      doc.fontSize(10).fillColor('#334155').text(`${String(item.order).padStart(2, '0')} — ${item.title}`);
      if (item.description) doc.fontSize(9).fillColor('#64748b').text(item.description, { indent: 12 });
    });
    doc.moveDown();
    doc.fillColor('#0f172a').fontSize(13).text('Timeline');
    (proposal.content.timeline || []).forEach((item) => {
      doc.fontSize(10).fillColor('#334155').text(`${item.week} — ${item.title}`);
    });
    doc.end();
  } catch (error) {
    return res.status(500).json({ message: error.message });
  }
}

export async function trackingTimeline(req, res) {
  const proposal = await Proposal.findOne({ _id: req.params.id, organization: req.user.organization })
    .populate('client', 'companyName contactName');
  if (!proposal) return res.status(404).json({ message: 'Proposal not found' });

  const minutes = Math.floor(proposal.totalViewTimeSeconds / 60);
  const seconds = proposal.totalViewTimeSeconds % 60;

  return res.json({
    proposalId: proposal._id,
    status: proposal.status,
    openCount: proposal.openCount,
    totalViewTime: `${minutes}m ${seconds}s`,
    firstOpenedAt: proposal.firstOpenedAt,
    lastViewedAt: proposal.lastViewedAt,
    events: proposal.events,
  });
}
